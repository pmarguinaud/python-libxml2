"""
Write docs/api.md from the docstrings of the package:

    python3 docs/make_api.py > docs/api.md

Classes come in the order of the DOM, then the rest, with their own methods and
properties: inherited ones are listed under the class that defines them.
"""
import inspect
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import xml_libxml as X                      # noqa: E402
from xml_libxml import SAX                  # noqa: E402

CLASSES = [
    ('Parser', X.Parser), ('Node', X.Node), ('Document', X.Document),
    ('Element', X.Element), ('Attr', X.Attr), ('Text', X.Text), ('Comment', X.Comment),
    ('CDATASection', X.CDATASection), ('PI', X.PI), ('DocumentFragment', X.DocumentFragment),
    ('Dtd', X.Dtd), ('Namespace', X.Namespace), ('NodeList', X.NodeList),
    ('NamedNodeMap', X.NamedNodeMap), ('AttributeHash', X.AttributeHash),
    ('XPathContext', X.XPathContext), ('XPathExpression', X.XPathExpression),
    ('Literal', X.Literal), ('Number', X.Number), ('Boolean', X.Boolean),
    ('RelaxNG', X.RelaxNG), ('Schema', X.Schema), ('Pattern', X.Pattern),
    ('RegExp', X.RegExp), ('Reader', X.Reader), ('InputCallback', X.InputCallback),
    ('Error', X.Error),
    ('SAX.SAX', SAX.SAX), ('SAX.Parser', SAX.Parser), ('SAX.Builder', SAX.Builder),
    ('SAX.Generator', SAX.Generator), ('SAX.Base', SAX.Base),
    ('SAX.NamespaceSupport', SAX.NamespaceSupport), ('SAX.DocumentLocator', SAX.DocumentLocator),
    ('SAX.AttributeNode', SAX.AttributeNode), ('SAX.SAXException', SAX.SAXException),
    ('SAX.ParseException', SAX.ParseException),
]

SKIP_BASES = (object, Exception, BaseException, list, str, int, float, dict)


def first_line(obj):
    doc = inspect.getdoc(obj) or ''
    return ' '.join(doc.strip().split('\n\n')[0].split())


def own_members(cls):
    found = []
    for name, value in sorted(vars(cls).items()):
        if name.startswith('_'):
            continue
        if any(name in vars(base) for base in cls.__mro__[1:] if base not in SKIP_BASES):
            continue                            # an override: listed with the base
        if inspect.isclass(value):
            continue
        kind = 'property' if inspect.isdatadescriptor(value) else (
            'constant' if isinstance(value, (int, str, float)) else 'method')
        found.append((name, kind, value))
    return found


def main():
    print('# xml_libxml API reference\n')
    print('Generated by `docs/make_api.py` from the docstrings. The Perl documentation of')
    print('XML::LibXML describes what each method does; `docs/migration.md` says how the')
    print('Python forms differ.\n')

    print('## Module functions\n')
    for name in X.__all__:
        value = getattr(X, name)
        if inspect.isfunction(value) or inspect.isbuiltin(value):
            print('- `%s`: %s' % (name, first_line(value)))
    constants = [n for n in X.__all__ + [n for n in dir(X) if n.startswith(('XML_PARSE', 'HTML_PARSE'))]
                 if isinstance(getattr(X, n), int)]
    print('\nConstants: %s.\n' % ', '.join('`%s`' % n for n in sorted(set(constants))))
    print('`xml_libxml.ErrNo` has the error codes of libxml2 (`ERR_*`, ...), as Perl\'s ErrNo.')
    print('`xml_libxml.Common` has the node type names of XML::LibXML::Common.\n')

    for title, cls in CLASSES:
        bases = [b.__name__ for b in cls.__bases__ if b not in (object,)]
        print('## %s%s\n' % (title, ' (%s)' % ', '.join(bases) if bases else ''))
        doc = first_line(cls)
        if doc:
            print(doc + '\n')
        members = own_members(cls)
        if not members:
            print('No members of its own.\n')
            continue
        for name, kind, value in members:
            line = first_line(value) if kind != 'constant' else repr(value)
            print('- `%s`%s%s' % (name, ' (property)' if kind == 'property' else '',
                                  ': ' + line if line else ''))
        print()


if __name__ == '__main__':
    main()
